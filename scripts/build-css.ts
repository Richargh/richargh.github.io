import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

export const cssBundleBanner = "/* Generated by scripts/build-css.ts. Do not edit directly. */";

const sourceRoots = ["_styles", "_ui/layouts", "_ui/blocks", "_ui/pages"] as const;

export async function discoverCssSources(rootDir = "."): Promise<string[]> {
  const groups = await Promise.all(sourceRoots.map((sourceRoot) => findCssFiles(join(rootDir, sourceRoot))));
  return groups.flat().sort((left, right) => sourceOrder(left).localeCompare(sourceOrder(right)));
}

export async function buildCssBundle(sourceFiles?: string[]): Promise<string> {
  const files = [...(sourceFiles ?? await discoverCssSources())].sort((left, right) => sourceOrder(left).localeCompare(sourceOrder(right)));
  const chunks = await Promise.all(files.map(async (file) => {
    const css = await readFile(file, "utf8");
    return `/* ${relative(".", file)} */\n${css.trim()}\n`;
  }));

  return `${cssBundleBanner}\n\n${chunks.join("\n")}`;
}

export async function writeCssBundle(outputFile = "generated/assets/css/style.css"): Promise<void> {
  const bundle = await buildCssBundle();
  await writeFile(outputFile, bundle, "utf8");
}

async function findCssFiles(directory: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return [];
    }
    throw error;
  }

  const files = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      return findCssFiles(path);
    }
    return extname(entry.name) === ".css" ? [path] : [];
  }));

  return files.flat().sort();
}

function sourceOrder(file: string): string {
  const normalized = file.replaceAll("\\", "/");
  const group = sourceRoots.findIndex((sourceRoot) => normalized.includes(`${sourceRoot}/`) || normalized.endsWith(sourceRoot));
  return `${group === -1 ? sourceRoots.length : group}:${normalized}`;
}

const currentFile = fileURLToPath(import.meta.url);
if (process.argv[1] === currentFile) {
  const outputFile = process.argv[2] ?? join(dirname(currentFile), "..", "generated/assets/css/style.css");
  await writeCssBundle(outputFile);
}
